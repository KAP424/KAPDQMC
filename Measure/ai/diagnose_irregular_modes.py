"""Independent Bloch-mode audit of the irregular-pattern crossover.

This reconstructs H and imaginary-time evolution in NumPy, without importing
the experiment or fit implementation.  Only new diagnostic files are written.
The default audit examines the gapped supercell momentum (pi, 0); --scan-grid
121 additionally reproduces the original exploratory shifted-grid scan of the
two m=4 patterns.  It is not necessary for the fixed-mode comparison.
"""
from __future__ import annotations

import argparse
import csv
from datetime import datetime, timezone
import hashlib
import json
import math
import os
from pathlib import Path
import subprocess

os.environ.setdefault("OPENBLAS_NUM_THREADS", "1")
os.environ.setdefault("MKL_NUM_THREADS", "1")
os.environ.setdefault("OMP_NUM_THREADS", "1")
import numpy as np


BASE = Path(__file__).resolve().parent
OUTPUT = BASE / "analysis_irregular_followup"
PLAN = OUTPUT / "plan.json"
THETAS = (0., 2., 4., 5., 6., 7., 8., 10., 12., 16., math.inf)
BETAS = (0., 1., 2.)


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def hamiltonian(m, kx, ky):
    """A(x,y) connects to B(x,y), B(x+1,y), B(x,y-1)."""
    h = np.zeros((2*m*m, 2*m*m), dtype=complex)
    for y in range(m):
        for x in range(m):
            a = 2*(x+m*y)
            for dx, dy in ((0, 0), (1, 0), (0, -1)):
                xx, yy = x+dx, y+dy
                b = 1+2*(xx % m + m*(yy % m))
                z = np.exp(1j*(kx*(xx//m)+ky*(yy//m)))
                h[a, b] += z
                h[b, a] += z.conjugate()
    return h


def prepare(meta, kx=math.pi, ky=0.):
    m = meta["m"]
    f = np.flatnonzero(np.array(list(meta["occupied_bits"])) == "1")
    p = m*m
    assert len(f) == p
    h = hamiltonian(m, kx, ky)
    energies, vectors = np.linalg.eigh(h)
    # No zero modes occur at the chosen diagnostic momentum.  The graph
    # representation below requires an invertible negative-energy overlap.
    assert energies[p-1] < -1e-9 and energies[p] > 1e-9
    a = vectors[f, :p].conj().T
    b = vectors[f, p:].conj().T
    s = np.linalg.svd(a, compute_uv=False)
    assert s[-1] > 1e-10
    x0 = np.linalg.solve(a.T, b.T).T
    return dict(h=h, e=energies, v=vectors, f=f, p=p, x0=x0,
                min_ground_overlap_sv=float(s[-1]),
                bandgap=float(energies[p]-energies[p-1]))


def orbitals(pre, theta):
    """Graph X=e^(-theta E+) B A^-1 e^(theta E-), then QR([I;X])."""
    p, e = pre["p"], pre["e"]
    x = (np.zeros_like(pre["x0"]) if math.isinf(theta) else
         np.exp(-theta*e[p:, None])*pre["x0"]*np.exp(theta*e[None, :p]))
    frame, _ = np.linalg.qr(np.vstack([np.eye(p), x]))
    return pre["v"] @ frame, float(np.linalg.svd(x, compute_uv=False)[0])


def measured(q, f, beta):
    raw = q.copy()
    empty = np.ones(q.shape[0], dtype=bool)
    empty[f] = False
    raw[empty] *= np.exp(-2*beta)
    return np.linalg.qr(raw)[0]


def fixed_rows(patterns):
    rows, matrices, modes = [], {}, {}
    for name, meta in patterns.items():
        pre = prepare(meta)
        modes[name] = pre
        qg, _ = orbitals(pre, math.inf)
        cg = qg @ qg.conj().T
        matrices[(name, "H", 0., 0.)] = pre["h"]
        for theta in THETAS:
            q, tangent = orbitals(pre, theta)
            c = q @ q.conj().T
            distance = float(np.linalg.norm(c-cg))
            for beta in BETAS:
                qb = measured(q, pre["f"], beta)
                cb = qb @ qb.conj().T
                min_f = float(np.linalg.svd(qb[pre["f"]], compute_uv=False)[-1]**2)
                s = pre["min_ground_overlap_sv"]
                expected_ground_min_f = s*s/(s*s+np.exp(-4*beta)*(1-s*s))
                rows.append(dict(pattern=name, m=meta["m"], kx=math.pi, ky=0.,
                    theta=theta, beta=beta,
                    ground_overlap_sigma_min=s,
                    positive_negative_energy_gap=pre["bandgap"],
                    graph_max_tangent=tangent,
                    premeasurement_ground_projector_frobenius=distance,
                    measured_min_F_principal_occupation=min_f,
                    ground_min_F_principal_occupation_formula=float(expected_ground_min_f),
                    measured_projector_error=float(np.linalg.norm(cb@cb-cb))))
                if theta in (4., 7., math.inf):
                    matrices[(name, "C", theta, beta)] = cb
    return rows, matrices


def julia_reference(patterns, matrices, julia):
    """Export existing FE Hamiltonians/projectors and compare entry by entry."""
    source = OUTPUT / "mode_fe_reference.jl"
    destination = OUTPUT / "mode_fe_reference.csv"
    entries = ",\n".join(f'    ({json.dumps(name)}, {meta["m"]}, '
                         f'{json.dumps(meta["occupied_bits"])})' for name, meta in patterns.items())
    source.write_text('''# Generated by diagnose_irregular_modes.py; small-block reference only.
using LinearAlgebra, Printf
BLAS.set_num_threads(1)
include('''+json.dumps((BASE / "fermion_experiment.jl").as_posix())+''')
import .FermionExperiment as FE
patterns = [
'''+entries+'''
]
open('''+json.dumps(destination.as_posix())+''', "w") do io
    println(io, "pattern,quantity,theta,beta,row,col,real,imag")
    function emit(name, quantity, theta, beta, matrix)
        for j in axes(matrix, 2), i in axes(matrix, 1)
            z = matrix[i,j]
            @printf(io, "%s,%s,%.17g,%.17g,%d,%d,%.17g,%.17g\\n",
                name, quantity, theta, beta, i, j, real(z), imag(z))
        end
    end
    for (name, m, bits) in patterns
        model = FE.BlochModel(6m, m)
        occupied = BitVector(c == '1' for c in bits)
        pre = FE.prepare_pattern(model, occupied; tol=1e-10)
        index = 4 # q=6, kx-index=3, ky-index=0: (pi,0)
        emit(name, "H", 0., 0., model.hamiltonians[index])
        for theta in (4., 7., Inf), beta in (0., 1., 2.)
            state = FE.measure(FE.evolve(pre, theta), beta)
            q = state.orbitals[index]
            emit(name, "C", theta, beta, q*q')
        end
    end
end
println("Wrote independent-implementation comparison reference")
''', encoding="utf-8")
    subprocess.run([julia, "--startup-file=no", "--threads=1", str(source)],
                   check=True, cwd=BASE, capture_output=True, text=True)
    reference = {key: np.zeros_like(value) for key, value in matrices.items()}
    seen = {key: set() for key in reference}
    with destination.open(newline="", encoding="utf-8") as stream:
        for row in csv.DictReader(stream):
            key = (row["pattern"], row["quantity"], float(row["theta"]), float(row["beta"]))
            i, j = int(row["row"])-1, int(row["col"])-1
            assert (i, j) not in seen[key]
            seen[key].add((i, j))
            reference[key][i, j] = complex(float(row["real"]), float(row["imag"]))
    results = []
    for key, actual in matrices.items():
        assert len(seen[key]) == actual.size
        diff = actual-reference[key]
        results.append(dict(pattern=key[0], quantity=key[1], theta=key[2], beta=key[3],
                            dimension=actual.shape[0], max_absolute_error=float(np.max(np.abs(diff))),
                            frobenius_error=float(np.linalg.norm(diff))))
    maximum = max(r["max_absolute_error"] for r in results)
    assert maximum < 1e-10, maximum
    with (OUTPUT / "mode_fe_comparison.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=results[0].keys())
        writer.writeheader()
        writer.writerows(results)
    return dict(status="PASS", tolerance=1e-10, matrices=len(results),
                max_absolute_error=maximum,
                max_frobenius_error=max(r["frobenius_error"] for r in results),
                theta=[4., 7., "Inf"], beta=list(BETAS),
                momentum="(pi,0) in supercell reciprocal coordinates, q=6",
                implementation="NumPy eigenbasis graph evolution versus existing FE energy-adapted evolution and QR",
                reference_source_sha256=digest(source),
                reference_csv_sha256=digest(destination),
                comparison_csv_sha256=digest(OUTPUT / "mode_fe_comparison.csv"),
                FE_sha256=digest(BASE / "fermion_experiment.jl"))


def scan(patterns, size):
    selected = {name: meta for name, meta in patterns.items() if meta["m"] == 4}
    minima = {name: {"sigma_min": 1.} for name in selected}
    samples = {name: [] for name in selected}
    for iy in range(size):
        for ix in range(size):
            kx, ky = 2*math.pi*(ix+.371)/size, 2*math.pi*(iy+.227)/size
            h = hamiltonian(4, kx, ky)
            e, v = np.linalg.eigh(h)
            for name, meta in selected.items():
                f = np.flatnonzero(np.array(list(meta["occupied_bits"])) == "1")
                s = float(np.linalg.svd(v[f, :16], compute_uv=False)[-1])
                samples[name].append(s)
                if s < minima[name]["sigma_min"]:
                    minima[name] = dict(sigma_min=s, kx=kx, ky=ky, bandgap=float(e[16]-e[15]))
    return dict(size=size, shifts=[.371, .227], endpoint=False, patterns={
        name: dict(**minima[name], quantile_probabilities=[0., .01, .05, .5, 1.],
                   quantiles=np.quantile(samples[name], [0., .01, .05, .5, 1.]).tolist())
        for name in selected})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--julia", default="julia")
    parser.add_argument("--scan-grid", type=int, default=0)
    args = parser.parse_args()
    plan = json.loads(PLAN.read_text(encoding="utf-8"))
    patterns = {name: plan["pattern_metadata"][name] for name in plan["patterns"]}
    rows, matrices = fixed_rows(patterns)
    OUTPUT.mkdir(exist_ok=True)
    csvpath = OUTPUT / "mode_diagnostics.csv"
    with csvpath.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)
    comparison = julia_reference(patterns, matrices, args.julia)
    # Principal occupations are invariant under right-unitary basis changes.
    formula_error = max(abs(r["measured_min_F_principal_occupation"]-
                            r["ground_min_F_principal_occupation_formula"])
                        for r in rows if math.isinf(r["theta"]))
    assert formula_error < 1e-12
    receipt = dict(status="PASS", generated_utc=datetime.now(timezone.utc).isoformat(),
        script_sha256=digest(__file__), plan_sha256=digest(PLAN),
        csv_sha256=digest(csvpath), numpy_version=np.__version__,
        patterns=patterns, rows=len(rows), kx=math.pi, ky=0.,
        overlap_definition="s = min singular value of Q_GS[F,:] = min singular value of V_negative^dagger P_initial. F denotes initially occupied sites; Q_GS has orthonormal columns.",
        projection_derivation="At a gapped momentum with A=V_negative^dagger P_initial invertible and B=V_positive^dagger P_initial, the evolved occupied span is V*[I; X(theta)], X(theta)=exp(-theta E_positive) B inv(A) exp(theta E_negative). QR only normalizes this span. This independent graph construction uses neither FE spectral rank cleaning nor its pivot algorithm.",
        occupation_derivation="Let Q_F^dagger Q_F have eigenvalues s_j^2. Q_E^dagger Q_E=I-Q_F^dagger Q_F. For M=diag(1 on F, epsilon on E), epsilon=exp(-2 beta), Q^dagger M^2 Q has eigenvalues s_j^2+epsilon^2(1-s_j^2). Normalizing M Q gives F-restricted principal occupations s_j^2/[s_j^2+epsilon^2(1-s_j^2)]. This function is increasing in s_j^2, so inserting the minimum overlap singular value gives the minimum principal occupation.",
        formula_max_absolute_error=formula_error,
        FE_comparison=comparison,
        limitations=[
            "The selected (pi,0) mode is gapped, away from the Dirac points. Its slow crossover is a microscopic projection transient, not a new Dirac node.",
            "A fixed-mode projector distance is evidence for a transient; it is not an entropy scaling coefficient and does not establish the unique origin of the full D(L) curvature.",
            "For finite beta, Q^dagger M^2 Q has eigenvalues between epsilon^2 and 1. Its condition number is at most exp(4 beta), at most exp(8) about 2981 for beta<=2. This filtering does not create a singular momentum surface where the unfiltered projector is smooth.",
            "A sharp but smooth momentum feature can produce a long crossover scale. This audit does not compute an asymptotic correlation length or prove all finite-beta states share the same corner coefficient.",
            "The fixed mode does not replace full momentum integration, entropy calculations, finite-size checks, or fits. The graph method here is restricted to a gapped momentum with invertible negative-energy overlap.",
        ])
    if args.scan_grid:
        assert args.scan_grid > 1
        receipt["optional_shifted_grid_scan"] = scan(patterns, args.scan_grid)
    (OUTPUT / "mode_diagnostics.json").write_text(json.dumps(receipt, indent=2, allow_nan=False), encoding="utf-8")
    print(json.dumps(dict(status=receipt["status"], rows=len(rows),
                         FE_comparison_max_error=comparison["max_absolute_error"],
                         formula_max_error=formula_error), indent=2))


if __name__ == "__main__":
    main()

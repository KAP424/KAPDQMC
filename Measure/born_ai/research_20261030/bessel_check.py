def load_rows():
    """One row per (L, beta), with every file sharing that key pooled.

    Two things went wrong here before.  (1) Every file became its own row, so a
    point split into shard files appeared as several rows with a fraction of the
    statistics each -- the L=18/beta=1.0 point exists twice (independently run,
    in data_matched_z and data_matched_largez) and was drawn twice at z=43.85.
    (2) The legacy beta=3, L=36 production value was appended as a hard-coded
    second row for a point the CSV already holds (see the comment below).
    """
    base = json.load(open(os.path.join(HERE, "baseline_D.json")))
    ks = np.array(sorted(int(k) for k in base))
    vs = np.array([base[str(k)]["D"] for k in ks])
    pool, meta = {}, {}
    for d in ("data_matched_z", "data_matched_largez"):
        for f in sorted(glob.glob(os.path.join(HERE, d, "*.csv"))):
            arr = read_csv(f)
            if arr is None:
                continue
            key = (int(arr["L"][0]), round(float(arr["beta"][0]), 4))
            pool.setdefault(key, []).append(np.asarray(arr["D"], dtype=float))
            meta.setdefault(key, []).append(os.path.basename(f))
            meta[key].append(float(arr["z"][0]))
    # The L=36, beta=3 point uses the CSV only, the same as headline_numbers.py,
    # so every script sees one value per point.  This script used to append the
    # legacy production value 0.24214 +- 0.00284 as a second, hard-coded row for
    # the same point.  That value is a genuinely independent measurement (the old
    # local-update MCMC: 12 chains, 2816 sweeps each, ESS ~7300, Rhat 1.0005; see
    # BORN_SCALING_RESULTS.md) and agrees with the CSV's 0.24294 +- 0.00978 to
    # 0.1 sigma, so dropping it moves z*(36) by 0.4% (6.29 -> 6.27) and changes
    # no quoted number.  It is not pooled because it comes from a different
    # sampler whose error bar rests on an autocorrelation estimate, and the
    # headline numbers deliberately use the exact independent sampler alone.
    rows = []
    for (L, b), arrs in sorted(pool.items()):
        zs = [m for m in meta[(L, b)] if isinstance(m, float)]
        Dv = np.concatenate(arrs)
        rows.append(dict(L=L, beta=b, z=zs[0], n=int(Dv.size),
                         mean=float(Dv.mean()),
                         sem=float(Dv.std(ddof=1) / np.sqrt(Dv.size)),
                         Dgs=float(np.interp(np.log(L), np.log(ks), vs)),
                         src="+".join(m for m in meta[(L, b)] if isinstance(m, str))))
    for r in rows:
        r["h"] = r["mean"] / r["Dgs"]
    return rows, ks, vs


def zstar_per_L(rows):
    out = {}
    for L in sorted({r["L"] for r in rows}):
        sel = sorted([r for r in rows if r["L"] == L], key=lambda r: r["z"])
        if len(sel) < 3:
            continue
        lz = np.log([r["z"] for r in sel])
        hh = np.array([r["h"] for r in sel])
        idx = np.where(np.diff(np.sign(hh - 0.5)))[0]
        if len(idx):
            i = idx[0]
            out[L] = float(np.exp(lz[i] + (0.5 - hh[i]) * (lz[i + 1] - lz[i])
                                 / (hh[i + 1] - hh[i])))
    return out


def fit_power(Ls, Z):
    A = np.vstack([np.ones_like(Ls), np.log(Ls)]).T
    coef, res, _, _ = np.linalg.lstsq(A, np.log(Z), rcond=None)
    pred = A @ coef
    rms = float(np.sqrt(np.mean((np.log(Z) - pred) ** 2)))
    return float(np.exp(coef[0])), float(coef[1]), rms



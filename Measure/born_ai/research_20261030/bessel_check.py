D70 = Decimal("1e-70")
D40 = Decimal("1e-45")


def D(x):
    """Decimal from a float / str / Decimal without binary-float debris."""
    if isinstance(x, Decimal):
        return x
    if isinstance(x, int):
        return Decimal(x)
    return Decimal(repr(float(x)))


# --------------------------------------------------------------------------
# Bessel functions by power series (no scipy)
# --------------------------------------------------------------------------

def bessel_i(n, x):
    """I_0(x) or I_1(x) in Decimal, power series, 80-digit accumulation."""
    x = D(x)
    h = x / 2
    h2 = h * h
    if n == 0:
        term = Decimal(1)
    elif n == 1:
        term = h
    else:
        raise ValueError
    s = term
    k = 0
    while True:
        k += 1
        if n == 0:
            term = term * h2 / (Decimal(k) * Decimal(k))
        else:
            term = term * h2 / (Decimal(k) * Decimal(k + 1))
        s += term
        if term < D70 * abs(s):
            break
        if k > 100000:
            raise RuntimeError("series did not converge")
    return s


def bessel_ratio(z):
    """I_1(2z)/I_0(2z) in Decimal."""
    x = 2 * D(z)
    return bessel_i(1, x) / bessel_i(0, x)


def bessel_limit(z):
    """2 [1 + I_1(2z)/I_0(2z)] in Decimal."""
    return 2 * (1 + bessel_ratio(z))


# --------------------------------------------------------------------------
# Exact finite-a channel factor
# --------------------------------------------------------------------------

def kappa(a, t):
    """kappa_a(t) = 1 - (1-t)^2 Z_{a-1}(t^2)/Z_a(t^2), exactly, in Decimal.

    Uses the exact identity Z_{a-1}(t^2) = sum_j C(a,j)^2 (1-j/a)^2 t^{2j},
    so both Z's come from one pass with no separate binomial table.
    Terms are generated by the ratio
        term_j / term_{j-1} = ((a-j+1)/j)^2 t^2.
    """
    a = int(a)
    t = D(t)
    t2 = t * t
    term = Decimal(1)
    S0 = Decimal(1)          # sum_j term_j
    S2 = Decimal(1)          # sum_j term_j (1-j/a)^2
    maxterm = Decimal(1)
    jpeak = 0
    j = 0
    while j < a:
        j += 1
        r = Decimal(a - j + 1) / Decimal(j)
        term = term * r * r * t2
        S0 += term
        f = Decimal(1) - Decimal(j) / Decimal(a)
        S2 += term * f * f
        if term > maxterm:
            maxterm = term
            jpeak = j
        if term < D40 * maxterm and j > jpeak:
            break
    R = S2 / S0
    om = Decimal(1) - t
    k = Decimal(1) - om * om * R
    return k, S0, S2


def kappa_over_t(a, t):
    t = D(t)
    k, _, _ = kappa(a, t)
    return k / t


def K_of_z(a, z):
    """kappa_a / t at fixed a with t = z/a, i.e. along the z = a t locus."""
    a = int(a)
    z = D(z)
    t = z / Decimal(a)
    return kappa_over_t(a, t)


# --------------------------------------------------------------------------
# Halfway point of the channel
# --------------------------------------------------------------------------

def halfway_z(a, lo=0.02, hi=2.0, target=Decimal(3), nbis=90):
    """z where kappa_a/t = target, along t = z/a. Bisection (monotone rise)."""
    a = int(a)
    flo = K_of_z(a, lo) - target
    fhi = K_of_z(a, hi) - target
    if flo * fhi > 0:
        return None, (float(flo), float(fhi))
    for _ in range(nbis):
        mid = (lo + hi) / 2
        fm = K_of_z(a, mid) - target
        if fm == 0:
            break
        if (fm > 0) == (fhi > 0):
            hi, fhi = mid, fm
        else:
            lo, flo = mid, fm
    return (lo + hi) / 2, None


def asym_halfway_z(target=3.0):
    """z solving 2[1+I_1(2z)/I_0(2z)] = target, in float, by bisection."""
    lo, hi = 1e-6, 50.0
    for _ in range(200):
        mid = math.sqrt(lo * hi)
        v = float(bessel_limit(mid))
        if v < target:
            lo = mid
        else:
            hi = mid
    return math.sqrt(lo * hi)



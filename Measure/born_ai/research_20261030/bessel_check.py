"""
Numerical test of the fixed-z Bessel limit of the Born channel factor kappa_a.

    Z_a((z/a)^2) = sum_j C(a,j)^2 (z/a)^{2j}  ->  I_0(2z)
    kappa_a/t  ->  2 [ 1 + I_1(2z)/I_0(2z) ]      (a -> inf, a t = z fixed)

PART 1: exact finite-a kappa at the project's real (L, beta) points.
PART 2: the crossover scale of the channel, and whether it scales like L^0.8,
        like L^1, or not at all.

All kappa values are computed in Decimal with 80 significant digits, because the
naive double-precision evaluation of 1 - (1-t)^2 Z_{a-1}/Z_a cancels ~11 digits
when z is O(0.1) (kappa ~ 2t while the subtracted pieces are O(1)).

numpy only. scipy is not installed; I_0 and I_1 are done by power series.

Outputs:
    figures/bessel_crossover.png
    bessel_check.json
"""

